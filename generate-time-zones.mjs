// Regenerates src/time-zones.ts: approximate coordinates for each IANA time
// zone (its principal city, from the tz database's zone.tab), keyed by every
// name the zone goes by, including the legacy ones some runtimes report
// (e.g. "Europe/Kiev" for "Europe/Kyiv").
//
// Usage: node generate-time-zones.mjs [path to tz data, default /usr/share/zoneinfo]
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const read = (file) =>
	readFileSync(join(dir, file), "utf8")
		.split("\n")
		.filter((line) => line && !line.startsWith("#"));

const version = readFileSync(join(dir, "tzdata.zi"), "utf8").match(
	/^# version (\S+)/
)?.[1];

// ±DDMM[SS] / ±DDDMM[SS] -> degrees
const toDegrees = (sign, digits, degreeDigits) => {
	const [d, m, s = "0"] = [
		digits.slice(0, degreeDigits),
		digits.slice(degreeDigits, degreeDigits + 2),
		digits.slice(degreeDigits + 2),
	];
	const value = +d + +m / 60 + +s / 3600;
	return +(sign === "-" ? -value : value).toFixed(4);
};

const coordinates = new Map();
for (const line of read("zone.tab")) {
	const [, iso6709, zone] = line.split("\t");
	const [, latSign, lat, lngSign, lng] = iso6709.match(
		/^([+-])(\d+)([+-])(\d+)$/
	);
	coordinates.set(zone, [
		toDegrees(latSign, lat, 2),
		toDegrees(lngSign, lng, 3),
	]);
}

const names = new Map(coordinates);
const alias = (name, target) => {
	if (!names.has(name) && coordinates.has(target)) {
		names.set(name, coordinates.get(target));
	}
};

for (const line of read("tzdata.zi")) {
	const [kind, target, name] = line.split(" ");
	if (kind === "L") alias(name, target);
}

// ICU (and so Intl) may canonicalize to a different name than tzdata does.
const canonical = (zone) => {
	try {
		return new Intl.DateTimeFormat("en", { timeZone: zone }).resolvedOptions()
			.timeZone;
	} catch {
		return null;
	}
};
const byCanonical = new Map();
for (const zone of coordinates.keys()) {
	const c = canonical(zone);
	if (c && !byCanonical.has(c)) byCanonical.set(c, zone);
}
for (const name of Intl.supportedValuesOf("timeZone")) {
	const target = byCanonical.get(canonical(name));
	if (target) alias(name, target);
}

const entries = [...names]
	.sort(([a], [b]) => a.localeCompare(b))
	.map(([name, [lat, lng]]) => `\t"${name}": [${lat}, ${lng}],`);

writeFileSync(
	"src/time-zones.ts",
	`// Generated by generate-time-zones.mjs from tz database ${version}; do not edit.

/** Latitude and longitude of each time zone's principal city. */
export const TIME_ZONE_COORDINATES: Record<string, [number, number]> = {
${entries.join("\n")}
};
`
);
console.log(`Wrote ${entries.length} time zones (tz ${version}).`);
